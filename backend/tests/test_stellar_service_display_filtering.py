"""Purpose: Unit tests for StellarService's display-facing filtering.

Description: Verifies per-frame photometry detection stubs (ids
ending ``:Star_<n>``, generated by VariabilityAnalyzer for every point
source in an imaging session's reference frame -- up to 2000 per
session) are excluded from user-facing listings (get_sources,
get_displayable_stellar_objects) but not from get_stellar_objects
itself, which internal round-trip callers like save_objects still
need in full.
"""

from unittest.mock import MagicMock

from astrometricslib import StellarObject
from backend.services.data.stellar_service import StellarService, _is_per_frame_photometry_detection


def _make_service(stellar_objects=None, planning_sources=None) -> StellarService:  # ruff: ignore[missing-type-function-argument]
    astrometrics = MagicMock()
    astrometrics.stars.list_objects.return_value = stellar_objects or []
    astrometrics.targets.list.return_value = []

    wayfinder = MagicMock()
    wayfinder.planning.get_sources.return_value = planning_sources or []

    return StellarService(config=MagicMock(), astrometrics=astrometrics, wayfinder=wayfinder)


def test_is_per_frame_photometry_detection_matches_generated_ids():  # ruff: ignore[missing-return-type-undocumented-public-function]
    """Verify the id pattern VariabilityAnalyzer generates is recognized."""
    assert _is_per_frame_photometry_detection("M 81:2026-01-14:0:0:Star_60") is True
    assert _is_per_frame_photometry_detection("M 81:2026-01-14:0:0:Star_1") is True


def test_is_per_frame_photometry_detection_does_not_match_real_names():  # ruff: ignore[missing-return-type-undocumented-public-function]
    """Verify ordinary catalog/target ids are never mistaken for detections."""
    assert _is_per_frame_photometry_detection("M 81") is False
    assert _is_per_frame_photometry_detection("Polaris") is False
    assert _is_per_frame_photometry_detection("My Custom Star_1") is False  # no colon before "Star_"


def test_get_displayable_stellar_objects_excludes_per_frame_detections():  # ruff: ignore[missing-return-type-undocumented-public-function]
    """Verify the display-facing listing drops VariabilityAnalyzer stubs."""
    catalog_star = StellarObject(id="Polaris", ra=37.95, dec=89.26)
    detection = StellarObject(id="M 81:2026-01-14:0:0:Star_60", ra=148.9, dec=69.0)

    service = _make_service(stellar_objects=[catalog_star, detection])

    displayable = service.get_displayable_stellar_objects()
    assert [obj.id for obj in displayable] == ["Polaris"]

    # get_stellar_objects itself must still return both -- internal callers
    # like save_objects()/find_or_create_by_position() round-trip the full set.
    assert [obj.id for obj in service.get_stellar_objects()] == ["Polaris", "M 81:2026-01-14:0:0:Star_60"]


def test_get_sources_excludes_per_frame_detections_with_real_coordinates():  # ruff: ignore[missing-return-type-undocumented-public-function]
    """Verify get_sources() drops solved (coordinate-bearing) detection stubs.

    Regression test: an earlier filter only caught pre-WCS-solve stubs
    (which lack ra/dec entirely); once a session is plate-solved these
    detections get real sky coordinates and slipped through into the
    Planetarium's star field as if they were catalog stars.
    """
    catalog_star = StellarObject(id="Polaris", ra=37.95, dec=89.26, magnitude=2.0)
    solved_detection = StellarObject(id="M 81:2026-01-14:0:0:Star_60", ra=148.9, dec=69.0)
    unsolved_detection = StellarObject(id="M 81:2026-01-14:0:0:Star_61", ra="", dec="")

    service = _make_service(
        planning_sources=[catalog_star, solved_detection, unsolved_detection],
    )

    sources = service.get_sources(ra=148.9, dec=69.0, radius=2.5)
    assert [source["id"] for source in sources] == ["Polaris"]


def test_stellar_object_has_spectra_and_has_photometry_computed_fields():  # ruff: ignore[missing-return-type-undocumented-public-function]
    """Verify StellarObject hasSpectra/hasPhotometry fields in model dump.

    Ensures that when StellarObject is serialized to JSON for RPC responses,
    hasSpectra and hasPhotometry computed properties are present and
    accurately reflect the presence of spectra or light curve photometry
    data.
    """
    star_with_spectra = StellarObject(
        id="Vega",
        spectrum_data_processed={"wavelengths_angstrom": [5000], "intensities": [1.0]},
    )
    star_with_photometry = StellarObject(
        id="Betelgeuse",
        light_curve={"timestamps": ["2026-01-01T00:00:00Z"], "magnitudes": [0.5]},
    )
    star_empty = StellarObject(id="EmptyStar")

    assert star_with_spectra.has_spectra is True
    assert star_with_spectra.has_photometry is False

    assert star_with_photometry.has_spectra is False
    assert star_with_photometry.has_photometry is True

    assert star_empty.has_spectra is False
    assert star_empty.has_photometry is False

    # Check serialized dictionary (by_alias=True)
    dumped = star_with_spectra.model_dump(by_alias=True)
    assert dumped["hasSpectra"] is True
    assert dumped["hasPhotometry"] is False
    assert dumped["plotData"] == {"wavelengths": [5000.0], "intensities": [1.0]}

    # Check RPC serialization
    from backend.services.rpc_protocol import serialize_rpc_result

    rpc_data = serialize_rpc_result(star_with_spectra)
    assert rpc_data["hasSpectra"] is True
    assert rpc_data["plotData"] == {"wavelengths": [5000.0], "intensities": [1.0]}
